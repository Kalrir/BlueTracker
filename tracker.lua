-- Read the player's Blue Magic spellbook and mark each spell learned/unlearned
-- accordingly. This is the single source of truth for the checkmarks. Guarded
-- so it silently no-ops until the player is loaded (and if HasSpell is absent).
local function SyncFromSpellbook()
    if not learned then return end
    local mm = AshitaCore and AshitaCore:GetMemoryManager()
    if not mm then return end
    local ok_p, player = pcall(function() return mm:GetPlayer() end)
    if not ok_p or not player then return end

    for _, r in ipairs(DB.SPELLS) do
        local sid = SID[r.key]
        if sid then
            local ok, has = pcall(function() return player:HasSpell(sid) end)
            if not ok then
                -- HasSpell not available in this build; stop trying so we don't
                -- spam pcall every frame. Leave current state as-is.
                spellbook_ok = false
                return
            end
            learned[r.key] = has and true or false
        end
    end
end

-- Strip FFXI auto-translate / color control bytes so plain substring
-- matching works on the "learns" message.
local function CleanText(s)
    if type(s) ~= 'string' then return '' end
    s = s:gsub('[\30\31].', '')   -- color start/end + palette byte
    s = s:gsub('\7', '')          -- line break marker
    s = s:gsub('\127.', '')       -- auto-translate brackets
    s = s:gsub('%z', '')          -- stray nulls
    return s
end

-- Does this spell pass the current filter set?
local function PassesFilter(r, needle, bluLvl)
    if cfg.bluemage_hide_learned and learned[r.key] then return false end
    if cfg.bluemage_only_my_level and bluLvl and r.lvl > bluLvl then return false end
    if roleFilter  ~= 'All' and r.role  ~= roleFilter  then return false end
    if traitFilter ~= 'All' and r.trait ~= traitFilter then return false end
    if famFilter   ~= 'All' and r.fam   ~= famFilter   then return false end
    if needle and needle ~= '' then
        local hay = (r.name .. ' ' .. r.trait .. ' ' .. r.elem .. ' '
                     .. (r.fam or '') .. ' ' .. (r.prop or '')):lower()
        if not hay:find(needle, 1, true) then return false end
    end
    return true
end

-- =========================
-- Filter combo
-- =========================
local function FilterCombo(label, id, current, options, width)
    imgui.SetNextItemWidth(width)
    local changed = current
    if imgui.BeginCombo(id, label .. ': ' .. current) then
        -- `id` already carries a "##" prefix, so append it directly (a single
        -- "##") to each option; adding another "##" would create "###", which
        -- makes ImGui hash only the shared suffix and collide every item's ID.
        if imgui.Selectable('All' .. id, current == 'All') then changed = 'All' end
        for _, opt in ipairs(options) do
            if imgui.Selectable(opt .. id, current == opt) then changed = opt end
        end
        imgui.EndCombo()
    end
    return changed
end

