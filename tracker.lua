        SetupColumns('##bm_rows')
        local shown = 0
        for _, r in ipairs(SORTED) do
            if PassesFilter(r, needle, bluLvl) then
                DrawSpellRow(r, bluLvl, skill)
                shown = shown + 1
            end
        end
        imgui.Columns(1)

        if shown == 0 then
            imgui.PushStyleColor(ImGuiCol_Text, { 0.55, 0.58, 0.72, 1.0 })
            imgui.Text('No spells match the current filters.')
            imgui.PopStyleColor(1)
        end

        imgui.EndChild()

        -- ---- Learned-from detail panel ----
        imgui.Separator()
        DrawDetailPanel()

        -- ---- Footer ----
        imgui.Separator()
        imgui.PushStyleColor(ImGuiCol_Text, { 0.50, 0.53, 0.66, 1.0 })
        imgui.Text(('Showing %d'):format(shown))
        imgui.PopStyleColor(1)
        imgui.SameLine(0, 10)
        imgui.PushStyleColor(ImGuiCol_Text, { 0.50, 0.53, 0.66, 1.0 })
        imgui.Text('MRL:')
        imgui.PopStyleColor(1)
        imgui.SameLine(0, 6)
        imgui.PushStyleColor(ImGuiCol_Text, STATUS_COL.green)
        imgui.Text('Green = Learnable')
        imgui.PopStyleColor(1)
        imgui.SameLine(0, 6)
        imgui.PushStyleColor(ImGuiCol_Text, { 0.50, 0.53, 0.66, 1.0 })
        imgui.Text('|')
        imgui.PopStyleColor(1)
        imgui.SameLine(0, 6)
        imgui.PushStyleColor(ImGuiCol_Text, STATUS_COL.yellow)
        imgui.Text('Yellow = Raise Skill lvl to Learn')
        imgui.PopStyleColor(1)
        imgui.SameLine(0, 10)
        imgui.PushStyleColor(ImGuiCol_Text, { 0.50, 0.53, 0.66, 1.0 })
        imgui.Text(spellbook_ok and '-   click a name for locations' or '-   spellbook read unavailable')
        imgui.PopStyleColor(1)

        imgui.Text('')   -- extra line of spacing below the legend

        imgui.EndTabItem()
    end  -- Spells tab

    -- Zones tab: search Blue Magic by zone, with a scalable map + player marker.
    if imgui.BeginTabItem('Zones') then
        RenderZoneTab()
        imgui.EndTabItem()
    end

    -- Settings tab. The gear / "/blutracker config" set vt._want_settings_tab so we
    -- programmatically select it here on the next frame.
    local set_flags = 0
    if vt and vt._want_settings_tab then
        set_flags = (type(ImGuiTabItemFlags_SetSelected) == 'number')
                    and ImGuiTabItemFlags_SetSelected or 2
        vt._want_settings_tab = false
    end
    if imgui.BeginTabItem('Settings', nil, set_flags) then
        RenderConfigTab()
        imgui.EndTabItem()
    end

    imgui.EndTabBar()

    -- Persist window position (applies regardless of the active tab).
    local px, py = imgui.GetWindowPos()
    if px and py then
        if math.abs(px - (cfg.bluemage_win_x or 0)) > 0.5
        or math.abs(py - (cfg.bluemage_win_y or 0)) > 0.5 then
            cfg.bluemage_win_x = px
            cfg.bluemage_win_y = py
            settings.save()
        end
    end
    end  -- if begin_ok and BeginTabBar
    imgui.End()

    PopWindowTheme()

    -- Sync close-button click back to cfg.
    if visible[1] ~= cfg.bluemage_open then
        cfg.bluemage_open = visible[1]
        if vt and vt.cfg_bluemage_open then vt.cfg_bluemage_open[1] = cfg.bluemage_open end
        settings.save()
    end
end

function M.command(e)
    -- Let the splash helper claim "/blutracker test*" first (else returns false).
    if BlueLearn then
        local ok, handled = pcall(function() return BlueLearn.command(e) end)
        if ok and handled then return true end
    end
    local a = e.command:lower():args()
    if #a == 0 then return false end
    if a[1] == '/blutracker' or a[1] == '/blut' then
        e.blocked = true
        if a[2] == 'config' or a[2] == 'settings' then
            cfg.bluemage_open = true
            if vt and vt.cfg_bluemage_open then vt.cfg_bluemage_open[1] = cfg.bluemage_open end
            if vt then vt._want_settings_tab = true end
            settings.save()
        elseif a[2] == 'floors' then
            M.debug_floors()
        else
            cfg.bluemage_open = not cfg.bluemage_open
            if vt and vt.cfg_bluemage_open then vt.cfg_bluemage_open[1] = cfg.bluemage_open end
            settings.save()
        end
        return true
    end
    return false
end

-- Diagnostic: print the current zone's map-floor geometry and how the currently
-- selected Zone-tab spell's spawn points get assigned. Helps pin down misplaced
-- dots on multi-map zones. Usage: /blutracker floors  (while standing in the
-- zone you're viewing on the Zone tab).
function M.debug_floors()
    local zid, zname = GetCurrentZone()
    local zoneName = zoneTabZone or zname
    print(('[BluTracker] floor debug for "%s" (current zone: %s / id %s)')
        :format(tostring(zoneName), tostring(zname), tostring(zid)))
    if not zoneName then return end
    local canon  = Canon(zoneName)
    local zoneid = ZoneIdOf(canon)
    local native = (gamemap and gamemap.floor_id_available and gamemap.floor_id_available()) and 'YES' or 'no'
    print(('  zoneid=%s  native floor fn: %s  in-zone: %s')
        :format(tostring(zoneid), native, tostring(zname and Canon(zname) == canon)))

    local floors = ZoneFloors(canon)
    if not floors then print('  (no live floor data - are you in game?)'); return end
    for _, f in ipairs(floors) do
        local b = f.bounds
        print(('  floor id %-3d  bounds x[%.0f..%.0f] z[%.0f..%.0f]  medY=%s')
            :format(f.floorid, b.minX, b.maxX, b.minZ, b.maxZ, tostring(f.medY)))
    end

    -- Selected spell's mobs, or all learnable if none selected.
    local zc = POS[canon]
    if not (zc and zc.mobs) then print('  (no spawn data for this zone)'); return end
    local mobset = {}
    if zoneTabSpellKey and LF.DATA[zoneTabSpellKey] then
        for _, row in ipairs(LF.DATA[zoneTabSpellKey]) do
            if Canon(row[3]) == canon then mobset[row[1]] = true end
        end
        print('  spell: ' .. tostring(zoneTabSpellKey))
    else
        print('  (no spell selected - showing nothing; select a spell first)')
        return
    end
    local inZone = zname and Canon(zname) == canon
    for name in pairs(mobset) do
        local pts = zc.mobs[name]
        if pts then
            for _, p in ipairs(pts) do
                local hint = inZone and gamemap.get_floor_id and gamemap.get_floor_id(p.x, p.y, p.z) or nil
                local f = PickFloor(floors, p.x, p.z, p.y, hint)
                print(('    %-18s x=%7.1f h=%6.1f z=%7.1f  -> floor %s  (native=%s)')
                    :format(name, p.x, p.y, p.z, f and tostring(f.floorid) or '?', tostring(hint)))
            end
        end
    end
end

-- Fallback only. When the spellbook read works it is authoritative and this
-- does nothing. On any client where IPlayer:HasSpell is unavailable
-- (spellbook_ok == false), this watches chat for the "learns <Spell>" message
-- and marks the spell so the tracker still updates as you learn.
function M.text_in(e)
    -- Feed the "Action Learned!" splash first (independent of the fallback).
    if BlueLearn then pcall(function() BlueLearn.text_in(e) end) end

    if not cfg or spellbook_ok then return end
    if cfg.bluemage_auto_learn == false then return end
    local msg = e.message or e.message_modified or e.text or ''
    local clean = CleanText(msg)
    if not clean:lower():find('learn', 1, true) then return end

    for _, r in ipairs(DB.SPELLS) do
        if clean:find(r.name, 1, true) then
            if not learned[r.key] then
                learned[r.key] = true
                print(('[BluTracker] Marked "%s" learned (%d/%d).')
                    :format(r.name, CountLearned(), DB.COUNT))
            end
            return
        end
    end
end

