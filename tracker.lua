-- =========================
-- Hover mini-map. Two modes:
--   * Calibrated: if the zone has a `calibration` block, world coords are
--     mapped into 512-reference map space exactly like Boussole
--     (texX = x*scalingX + offsetX, texY = z*scalingY + offsetY), so the plot
--     matches the in-game map's orientation and proportions. If a real map
--     image is present at  <addon>/maps/<image>  it is drawn underneath the
--     markers (best-effort; any failure silently falls back to the grid).
--   * Fallback: a plain data-bounds grid (no calibration needed).
-- Returns true if it had data to draw.
-- =========================
-- Base sizes; the actual pixel size is the base times the user's map scale.
local MAP_BASE      = 240   -- hover mini-map (Spells / Tracker) -- scaled by MapScale()
local MAP_BASE_ZONE = 360   -- fallback size for the Zone-tab map
local MAP_ZONE_MIN  = 300   -- Zone-tab map fills its pane, clamped to this range
local MAP_ZONE_MAX  = 480   -- (the Zone-tab map is NOT affected by the map-scale setting)
local MAP_PAD       = 10

-- User-configurable map size multiplier (clamped to a sane range).
local function MapScale()
    local s = cfg and cfg.bluemage_map_scale or 1.0
    if type(s) ~= 'number' or s <= 0 then s = 1.0 end
    if s < 0.5 then s = 0.5 elseif s > 3.0 then s = 3.0 end
    return s
end

local function u32(r, g, b, a)
    return imgui.GetColorU32({ r, g, b, a or 1.0 })
end

-- Lazy, guarded PNG loader. Returns a texture pointer usable as an ImGui image
-- id, or nil. Never throws; caches success/failure per file so we try once.
local _tex_cache = {}
local _cdef_done = false
local function load_map_texture(imageName)
    if not imageName or imageName == '' then return nil end
    if _tex_cache[imageName] ~= nil then
        return _tex_cache[imageName] or nil
    end
    local ok, tex = pcall(function()
        if not addon or not addon.path then return nil end
        local base = tostring(addon.path):gsub('[\\/]+$', '')
        local path = base .. '\\maps\\' .. imageName
        local f = io.open(path, 'rb'); if not f then return nil end; f:close()
        local ffi  = require('ffi')
        local d3d8 = require('d3d8')
        local dev  = d3d8.get_device()
        if not dev then return nil end
        if not _cdef_done then
            ffi.cdef[[
                int32_t D3DXCreateTextureFromFileA(void* device, const char* file, void** texture);
            ]]
            _cdef_done = true
        end
        local out = ffi.new('void*[1]')
        local hr = ffi.C.D3DXCreateTextureFromFileA(dev, path, out)
        if hr ~= 0 or out[0] == nil then return nil end
        return d3d8.gc_safe_release(ffi.cast('IDirect3DBaseTexture8*', out[0]))
    end)
    local result = ok and tex or nil
    _tex_cache[imageName] = result or false
    return result
end

