-- =========================
-- Learn-readiness status (for green/yellow/dim colouring)
--   green  : your Blue Magic skill already meets the learn requirement
--   yellow : you are a high enough level (>= MRL) but your skill is too low
--   dim    : you are below the level range for the spell
--   none   : BLU is not your main job, so we can't judge readiness
-- =========================
local STATUS_COL = {
    green  = { 0.45, 0.92, 0.52, 1.0 },
    yellow = { 0.96, 0.82, 0.36, 1.0 },
    dim    = { 0.55, 0.57, 0.66, 1.0 },
}

local function LearnStatus(key, bluLvl, skill)
    if bluLvl == nil then return 'none' end
    local mrl   = MRL[key]   or 999
    local reqsk = REQSK[key] or 0
    if skill ~= nil then
        if skill >= reqsk then return 'green' end   -- enough skill: learnable now
        if bluLvl >= mrl   then return 'yellow' end  -- in level range, skill too low
        return 'dim'
    end
    -- Skill couldn't be read: fall back to level vs MRL (no yellow state).
    if bluLvl >= mrl then return 'green' else return 'dim' end
end

