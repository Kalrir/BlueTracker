                            u32(COL_GOOD[1], COL_GOOD[2], COL_GOOD[3], 1.0), ('- Lv %d'):format(tier))
                    end)
                end
                if open then
                    RenderTraitBody(t, visible, myLvl, learnedCount)
                    imgui.Separator()
                end
