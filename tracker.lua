-- =========================
-- Learn-readiness status (for green/yellow/dim colouring)
--   green  : your Blue Magic skill already meets the learn requirement
--   yellow : you are a high enough level (>= MRL) but your skill is too low
--   dim    : you are below the level range for the spell
--   none   : BLU is not your main job, so we can't judge readiness
-- =========================
local STATUS_COL = {
    green  = { 0.45, 0.92, 0.52, 1.0 },
    yellow = { 0.96, 0.82, 0.36, 1.0 },
    dim    = { 0.55, 0.57, 0.66, 1.0 },
}

local function LearnStatus(key, bluLvl, skill)
    if bluLvl == nil then return 'none' end
    local mrl   = MRL[key]   or 999
    local reqsk = REQSK[key] or 0
    if skill ~= nil then
        if skill >= reqsk then return 'green' end   -- enough skill: learnable now
        if bluLvl >= mrl   then return 'yellow' end  -- in level range, skill too low
        return 'dim'
    end
    -- Skill couldn't be read: fall back to level vs MRL (no yellow state).
    if bluLvl >= mrl then return 'green' else return 'dim' end
end

-- =========================
-- Row (drawn inside an active 7-column context)
-- =========================
local function DrawSpellRow(r, bluLvl, skill)
    local isLearned = learned[r.key] and true or false
    local status    = LearnStatus(r.key, bluLvl, skill)
    local statusCol  = STATUS_COL[status]

    -- col 0: read-only learned indicator (driven by the player's spellbook).
    if isLearned then
        imgui.PushStyleColor(ImGuiCol_Text, { 0.45, 0.95, 0.55, 1.0 })
        imgui.Text('[X]')
    else
        imgui.PushStyleColor(ImGuiCol_Text, { 0.45, 0.48, 0.60, 1.0 })
        imgui.Text('[ ]')
    end
    imgui.PopStyleColor(1)
    imgui.NextColumn()

    -- Neutral base colour for the non-status columns.
    local baseCol = (status == 'dim') and { 0.50, 0.52, 0.62, 1.0 } or { 0.82, 0.85, 0.94, 1.0 }
    -- green = your skill is high enough now, yellow = in range but skill too
    -- low, dim = below the level range.
    local mrl = MRL[r.key]
    if mrl then
        imgui.PushStyleColor(ImGuiCol_Text, statusCol or { 0.62, 0.62, 0.70, 1.0 })
        imgui.Text(tostring(mrl))
        imgui.PopStyleColor(1)
    else
        imgui.PushStyleColor(ImGuiCol_Text, { 0.45, 0.48, 0.60, 1.0 })
        imgui.Text('-')
        imgui.PopStyleColor(1)
    end
    imgui.NextColumn()

    -- col 2: LVL (level the spell can be set / used)
    imgui.PushStyleColor(ImGuiCol_Text, (status == 'dim') and { 0.62, 0.56, 0.56, 1.0 } or { 0.70, 0.73, 0.85, 1.0 })
    imgui.Text(tostring(r.lvl))
    imgui.PopStyleColor(1)
    imgui.NextColumn()

    -- col 3: Spell name. Coloured by learn-readiness (green/yellow/dim); when
    -- BLU isn't your main job, falls back to the role colour. " *" = Horizon change.
    imgui.PushStyleColor(ImGuiCol_Text, statusCol or (ROLE_COLORS[r.role] or baseCol))
    if imgui.Selectable(r.name .. (r.hz and ' *' or '') .. '##nm_' .. r.key, selectedKey == r.key) then
        selectedKey = r.key
    end
    imgui.PopStyleColor(1)
    if imgui.IsItemHovered() then
        imgui.BeginTooltip()
        imgui.Text(r.name)
        imgui.Separator()
        imgui.PushStyleColor(ImGuiCol_Text, { 0.70, 0.73, 0.85, 1.0 })
        imgui.Text(('%s  -  %s'):format(
            (r.kind == 'Phys') and 'Physical' or 'Magical', r.role))
        imgui.Text(('Usable at Lv %d   -   Learn by Lv %s (capped skill)'):format(r.lvl, MRL[r.key] and tostring(MRL[r.key]) or '?'))
        imgui.Text(('Needs Blue Magic skill %d  -  skill+ gear can learn earlier'):format(REQSK[r.key] or 0))
        imgui.Text('Type: ' .. r.elem)
        imgui.Text('Trait when set: ' .. r.trait)
        imgui.Text('Effect / SC: ' .. (r.prop or '-'))
        imgui.Text('Learn from: ' .. ((r.fam and r.fam ~= '\226\128\148') and r.fam or 'not catalogued'))
        imgui.Text('MP: ' .. (r.mp and tostring(r.mp) or '?'))
        imgui.PopStyleColor(1)
        if r.hz then
            imgui.Separator()
            imgui.PushStyleColor(ImGuiCol_Text, { 1.00, 0.72, 0.35, 1.0 })
            imgui.Text('HorizonXI-specific change vs retail.')
            imgui.PopStyleColor(1)
        end
        imgui.Separator()
        imgui.PushStyleColor(ImGuiCol_Text, isLearned and { 0.55, 0.90, 0.60, 1.0 } or { 0.55, 0.58, 0.72, 1.0 })
        imgui.Text(isLearned and 'Learned' or 'Not yet learned')
        imgui.PopStyleColor(1)
        if not isLearned and status ~= 'none' then
            imgui.PushStyleColor(ImGuiCol_Text, statusCol or { 0.55, 0.58, 0.72, 1.0 })
            if status == 'green' then
                imgui.Text('Your skill is high enough - learnable now')
            elseif status == 'yellow' then
                imgui.Text('In level range - raise Blue Magic skill to learn')
            else
                imgui.Text('Below the level range for this spell')
            end
            imgui.PopStyleColor(1)
        end
        imgui.EndTooltip()
    end
    imgui.NextColumn()

    -- col 4: Type  ("P Slashing" / "M Fire")
    imgui.PushStyleColor(ImGuiCol_Text, (status == 'dim') and baseCol or (ELEM_COLORS[r.elem] or baseCol))
    imgui.Text(((r.kind == 'Phys') and 'P ' or 'M ') .. r.elem)
    imgui.PopStyleColor(1)
    imgui.NextColumn()

    -- col 5: Trait
    imgui.PushStyleColor(ImGuiCol_Text, baseCol)
    imgui.Text(r.trait == 'None' and '-' or r.trait)
    imgui.PopStyleColor(1)
    imgui.NextColumn()

    -- col 6: Learn-from family
    imgui.PushStyleColor(ImGuiCol_Text, baseCol)
    imgui.Text(r.fam or '\226\128\148')
    imgui.PopStyleColor(1)
    imgui.NextColumn()

    -- col 7: Tracking checkbox - clickable, user-controlled.
    local isTracked = tracked[r.key] and true or false
    imgui.PushStyleColor(ImGuiCol_Text, isTracked and { 0.55, 0.85, 1.00, 1.0 } or { 0.40, 0.43, 0.55, 1.0 })
    if imgui.Selectable((isTracked and '[X]##trk_' or '[ ]##trk_') .. r.key, isTracked) then
        tracked[r.key] = not isTracked
        settings.save()
    end
    imgui.PopStyleColor(1)
    if imgui.IsItemHovered() then
        imgui.SetTooltip(isTracked and 'Tracked - click to untrack' or 'Click to track this spell')
    end
    imgui.NextColumn()
end

