-- Player's BLU main-job level, or nil if BLU is not the main job. Uses the
-- party self-slot (index 0), matching how Renkei reads job/level here.
local function GetBluLevel()
    local mm = AshitaCore and AshitaCore:GetMemoryManager()
    if not mm then return nil end
    local party = mm:GetParty()
    if not party then return nil end
    local ok_job, job = pcall(function() return party:GetMemberMainJob(0) end)
    if not ok_job or job ~= BLU_JOB_ID then return nil end
    local ok_lvl, lvl = pcall(function() return party:GetMemberMainJobLevel(0) end)
    if not ok_lvl then return nil end
    return lvl
end

-- Player's current Blue Magic combat skill value (skill id 43), or nil if it
-- can't be read on this client. Handles the binding returning either a skill
-- object (with :GetSkill()) or a plain number.
local BLUE_MAGIC_SKILL_ID = 43
local function GetBlueSkill()
    local mm = AshitaCore and AshitaCore:GetMemoryManager()
    if not mm then return nil end
    local ok_p, player = pcall(function() return mm:GetPlayer() end)
    if not ok_p or not player then return nil end
    local ok, cs = pcall(function() return player:GetCombatSkill(BLUE_MAGIC_SKILL_ID) end)
    if not ok or cs == nil then return nil end
    if type(cs) == 'number' then return cs end
    local ok2, val = pcall(function() return cs:GetSkill() end)
    if ok2 and type(val) == 'number' then return val end
    return nil
end

-- Current zone id and its formatted name (matching learn-from zone strings),
-- or nil if not available / not catalogued.
local function GetCurrentZone()
    local mm = AshitaCore and AshitaCore:GetMemoryManager()
    if not mm then return nil, nil end
    local party = mm:GetParty()
    if not party then return nil, nil end
    local ok, zid = pcall(function() return party:GetMemberZone(0) end)
    if not ok or not zid or zid == 0 then return nil, nil end
    return zid, ZONES[zid]
end

-- Spells learnable in the given zone name: unlearned spells whose learn-from
-- data lists a mob in that zone. Returns an array of
-- { rec, mobs = { {mob, level}, ... } } (every mob for that spell in the zone).
local function SpellsInZone(zoneName)
    local out = {}
    if not zoneName then return out end
    for _, r in ipairs(SORTED) do
        if not learned[r.key] then
            local rows = LF.DATA[r.key]
            if rows then
                local mobs = {}
                for _, row in ipairs(rows) do
                    if row[3] == zoneName then
                        mobs[#mobs + 1] = { row[1], row[2] }
                    end
                end
                if #mobs > 0 then
                    out[#out + 1] = { rec = r, mobs = mobs }
                end
            end
        end
    end
    return out
end

local function CountLearned()
    local n = 0
    for _, r in ipairs(DB.SPELLS) do
