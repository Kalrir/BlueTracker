function M.init(host)
    cfg         = host.cfg
    vt          = host.vt
    settings    = host.settings
    helpers     = host.helpers
    default_cfg = host.default_config

    -- Bind the learned subtable (settings.load already merged defaults).
    if not cfg.bluemage_data then cfg.bluemage_data = M.default_data end
    if not cfg.bluemage_data.learned then cfg.bluemage_data.learned = T{} end
    learned = cfg.bluemage_data.learned

    -- Bind the user-selected "tracked" spells (persisted).
    if not cfg.bluemage_track_data then cfg.bluemage_track_data = M.default_track end
    if not cfg.bluemage_track_data.tracked then cfg.bluemage_track_data.tracked = T{} end
    tracked = cfg.bluemage_track_data.tracked

    -- Make sure every known spell has an entry (handles data additions).
    for _, r in ipairs(DB.SPELLS) do
        if learned[r.key] == nil then learned[r.key] = false end
        if tracked[r.key] == nil then tracked[r.key] = false end
    end

    -- Checkmarks are driven by the player's spellbook. Sync once now (runs
    -- again on a throttle in render as the player loads / learns spells).
    spellbook_ok    = true
    frame_counter   = 0
    last_sync_frame = 0
    SyncFromSpellbook()

    -- Bring up the "Action Learned!" splash helper.
    if BlueLearn then
        pcall(function() BlueLearn.init(host) end)
        -- Restrict the "Action Learned!" splash to real Blue Magic, so other
        -- jobs' spell learns (e.g. RDM scribing) don't trigger it.
        pcall(function()
            local set = {}
            for _, r in ipairs(DB.SPELLS) do set[r.name:lower()] = true end
            BlueLearn.set_valid_spells(set)
        end)
    end
end

-- =========================
-- Separate "tracker" window
-- =========================
local TRACK_WIN_W = 440
local TRACK_WIN_H = 380

-- Per-spell expand/collapse state in the tracker window.
local trk_expanded = {}

-- Leading number of a level string ("3-8" -> 3, "33" -> 33) for sorting.
local function MinLvl(s)
    local n = tostring(s):match('^%d+')
    return n and tonumber(n) or 0
end

-- A collapsible entry: header line (click to expand) + an indented mob list.
--   mobs      : array of { mob, level [, zone] }
--   show_zone : include the zone on each mob line (specific mode = all zones)
local function TrackerEntry(r, bluLvl, skill, mobs, show_zone, zone_name)
    local isL    = learned[r.key] and true or false
    local status = LearnStatus(r.key, bluLvl, skill)
    local open   = trk_expanded[r.key] and true or false

    local arrow = (#mobs > 0) and (open and '[-] ' or '[+] ') or '    '
    local label = arrow .. ('Lv%02d  '):format(r.lvl) .. r.name .. (isL and '  [X]' or '')

    imgui.PushStyleColor(ImGuiCol_Text, STATUS_COL[status] or { 0.82, 0.85, 0.94, 1.0 })
    if imgui.Selectable(label .. '##trkhdr_' .. r.key, open) then
        trk_expanded[r.key] = not open
    end
    imgui.PopStyleColor(1)

    if not open then return end
    if #mobs == 0 then
        imgui.PushStyleColor(ImGuiCol_Text, { 0.55, 0.58, 0.72, 1.0 })
        imgui.Text('  learn from the ' .. (r.fam or 'listed') .. ' family')
        imgui.PopStyleColor(1)
        return
    end

    -- Sorted copy: Area, Mob, then Lvl. Zone mode has a single area (shown in
    -- the header) so it lists Mob, Lvl only.
    local rows = {}
    for _, m in ipairs(mobs) do rows[#rows + 1] = m end
    if show_zone then
        table.sort(rows, function(a, b)
            if (a[3] or '') ~= (b[3] or '') then return (a[3] or '') < (b[3] or '') end
            if a[1] ~= b[1] then return a[1] < b[1] end
            return MinLvl(a[2]) < MinLvl(b[2])
        end)
    else
        table.sort(rows, function(a, b)
            if a[1] ~= b[1] then return a[1] < b[1] end
            return MinLvl(a[2]) < MinLvl(b[2])
        end)
    end

    -- Aligned columns via measured text widths + absolute SameLine, so each
    -- column sits after the widest entry in the one before it (no overlap, and
    -- the level never gets squeezed into a fixed narrow column).
    local function tw(s)
        local w = imgui.CalcTextSize(s)
        return (type(w) == 'number') and w or 0
    end

    if show_zone then
        local maxA, maxM = 0, 0
        for _, m in ipairs(rows) do
            local a = tw('  ' .. (m[3] or '')); if a > maxA then maxA = a end
            local mm = tw(m[1]);                if mm > maxM then maxM = mm end
        end
        local mob_x = maxA + 16
        local lvl_x = mob_x + maxM + 16
        for _, m in ipairs(rows) do
            imgui.PushStyleColor(ImGuiCol_Text, { 0.62, 0.72, 0.60, 1.0 })  -- Area
            imgui.Text('  ' .. (m[3] or ''))
            imgui.PopStyleColor(1)
            imgui.SameLine(mob_x, 0)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.78, 0.80, 0.90, 1.0 })  -- Mob
            imgui.Text(m[1])
            imgui.PopStyleColor(1)
            do  -- hover the mob name for its spawn mini-map
                local zn = m[3] or zone_name
                if imgui.IsItemHovered() and zn and POS[zn] and POS[zn].mobs[m[1]] then
                    imgui.BeginTooltip(); DrawMobMap(zn, m[1]); imgui.EndTooltip()
                end
            end
            imgui.SameLine(lvl_x, 0)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.62, 0.66, 0.78, 1.0 })  -- Lvl
            imgui.Text('Lv ' .. tostring(m[2]))
            imgui.PopStyleColor(1)
        end
    else
        local maxM = 0
        for _, m in ipairs(rows) do
            local mm = tw('  ' .. m[1]); if mm > maxM then maxM = mm end
        end
        local lvl_x = maxM + 16
        for _, m in ipairs(rows) do
            imgui.PushStyleColor(ImGuiCol_Text, { 0.78, 0.80, 0.90, 1.0 })  -- Mob
            imgui.Text('  ' .. m[1])
            imgui.PopStyleColor(1)
            do  -- hover the mob name for its spawn mini-map
                local zn = m[3] or zone_name
                if imgui.IsItemHovered() and zn and POS[zn] and POS[zn].mobs[m[1]] then
                    imgui.BeginTooltip(); DrawMobMap(zn, m[1]); imgui.EndTooltip()
                end
            end
            imgui.SameLine(lvl_x, 0)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.62, 0.66, 0.78, 1.0 })  -- Lvl
            imgui.Text('Lv ' .. tostring(m[2]))
            imgui.PopStyleColor(1)
        end
    end
end

local function RenderTracker()
    if not cfg then return end
    if not tracked or not learned then return end
    local mode = cfg.bluemage_track_mode or 'off'
    if mode == 'off' then return end
    if cfg.bluemage_hide_on_menu and in_game_menu_open() then return end

    imgui.SetNextWindowSize({ TRACK_WIN_W, TRACK_WIN_H }, ImGuiCond_FirstUseEver)
    imgui.SetNextWindowPos({ cfg.bluemage_track_win_x or 910, cfg.bluemage_track_win_y or 200 }, ImGuiCond_FirstUseEver)

    PushWindowTheme(BgColor())
    local flags = 0
    if cfg.bluemage_lock_ui then
        flags = bit.bor(flags, ImGuiWindowFlags_NoMove, ImGuiWindowFlags_NoResize)
    end

    local visible = { true }
    local begin_ok = imgui.Begin('Blue Magic Tracker', visible, flags)
    if begin_ok then
        local bluLvl = GetBluLevel()
        local skill  = GetBlueSkill()

        if mode == 'specific' then
            imgui.PushStyleColor(ImGuiCol_Text, { 0.80, 0.90, 1.00, 1.0 })
            imgui.Text('Tracked spells')
            imgui.PopStyleColor(1)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.50, 0.53, 0.66, 1.0 })
            imgui.Text('click a spell to list every mob / zone')
            imgui.PopStyleColor(1)
            imgui.Separator()
            imgui.BeginChild('##bm_trk_list', { 0, 0 })
            local any = false
            for _, r in ipairs(SORTED) do
                if tracked[r.key] then
                    any = true
                    TrackerEntry(r, bluLvl, skill, LF.DATA[r.key] or {}, true)
                end
            end
            if not any then
                imgui.PushStyleColor(ImGuiCol_Text, { 0.55, 0.58, 0.72, 1.0 })
                imgui.Text('No spells tracked yet.')
                imgui.Text('Tick the "Trk" column in the main list.')
                imgui.PopStyleColor(1)
            end
            imgui.EndChild()

        elseif mode == 'zone' then
            local zid, zname = GetCurrentZone()
            imgui.PushStyleColor(ImGuiCol_Text, { 0.80, 0.90, 1.00, 1.0 })
            imgui.Text('Learnable in current zone')
            imgui.PopStyleColor(1)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.72, 0.82, 0.72, 1.0 })
            imgui.Text(zname or ('Zone ' .. tostring(zid or '?') .. ' (not catalogued)'))
            imgui.PopStyleColor(1)
            imgui.Separator()
            imgui.BeginChild('##bm_trk_list', { 0, 0 })
            local list = SpellsInZone(zname)
            if #list == 0 then
                imgui.PushStyleColor(ImGuiCol_Text, { 0.55, 0.58, 0.72, 1.0 })
                imgui.Text('No unlearned spells to grab here.')
                imgui.PopStyleColor(1)
            else
                for _, item in ipairs(list) do
                    TrackerEntry(item.rec, bluLvl, skill, item.mobs, false, zname)
                end
            end
            imgui.EndChild()
        end

        -- Persist window position.
        local px, py = imgui.GetWindowPos()
        if px and py then
            if math.abs(px - (cfg.bluemage_track_win_x or 0)) > 0.5
            or math.abs(py - (cfg.bluemage_track_win_y or 0)) > 0.5 then
                cfg.bluemage_track_win_x = px
                cfg.bluemage_track_win_y = py
                settings.save()
            end
        end
    end
    imgui.End()
    PopWindowTheme()

    -- Closing the tracker window turns tracking off.
    if not visible[1] then
        cfg.bluemage_track_mode = 'off'
        settings.save()
    end
end

