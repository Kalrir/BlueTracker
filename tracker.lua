function M.render()
    if not cfg then return end

    -- Drive the "Action Learned!" splash fade/queue every frame, before any
    -- of the window early-returns below.
    if BlueLearn then pcall(function() BlueLearn.render() end) end

    -- Keep the learned checkmarks in sync with the player's spellbook. Runs
    -- regardless of which windows are open.
    if spellbook_ok then
        frame_counter = frame_counter + 1
        if frame_counter - last_sync_frame >= SYNC_INTERVAL then
            last_sync_frame = frame_counter
            SyncFromSpellbook()
        end
    end

    -- Capture the game's exact map-floor for the zone you're standing in (once),
    -- automatically -- no need to open the Zone tab. Near-free after the first
    -- successful capture per zone (ScanZoneFloors early-outs once cached).
    pcall(function()
        local _, cz = GetCurrentZone()
        if cz then
            local canon = Canon(cz)
            if not nativeScanned[canon]
               and gamemap and gamemap.floor_id_available and gamemap.floor_id_available() then
                ScanZoneFloors(canon)
            end
        end
    end)

    -- The separate tracker window renders independently of the main window
    -- (it shows whenever the track mode is not 'off').
    RenderTracker()

    if not cfg.bluemage_open then return end
    if cfg.bluemage_hide_on_menu and in_game_menu_open() then return end

    imgui.SetNextWindowSize({ WINDOW_WIDTH, WINDOW_HEIGHT }, ImGuiCond_FirstUseEver)
    imgui.SetNextWindowPos({ cfg.bluemage_win_x or 340, cfg.bluemage_win_y or 200 }, ImGuiCond_FirstUseEver)

    PushWindowTheme(BgColor())

    local flags = ImGuiWindowFlags_NoScrollbar
    if cfg.bluemage_lock_ui then
        flags = bit.bor(flags, ImGuiWindowFlags_NoMove, ImGuiWindowFlags_NoResize)
    end

    local visible = { cfg.bluemage_open }
    local title = 'Blue Magic Tracker - V ' .. tostring((addon and addon.version) or '1.0')
    local begin_ok = imgui.Begin(title, visible, flags)

    -- Title-bar gear jumps to the in-window Settings tab.
    if helpers and helpers.draw_titlebar_gear then
        helpers.draw_titlebar_gear('blu', 1.0, function()
            if vt then vt._want_settings_tab = true end
        end)
    end

    if begin_ok and imgui.BeginTabBar('##blu_main_tabs', ImGuiTabBarFlags_None) then
    if imgui.BeginTabItem('Spells') then
        local bluLvl  = GetBluLevel()
        local skill   = GetBlueSkill()
        local total   = DB.COUNT
        local nLearn  = CountLearned()
        local frac    = (total > 0) and (nLearn / total) or 0

        -- ---- Progress ----
        imgui.PushStyleColor(ImGuiCol_Text, { 0.80, 0.90, 1.00, 1.0 })
        if bluLvl then
            if skill then
                imgui.Text(('Blue Mage   -   Lv %d   -   Blue Magic Skill %d'):format(bluLvl, skill))
            else
                imgui.Text(('Blue Mage   -   Lv %d'):format(bluLvl))
            end
        else
            imgui.Text('Blue Mage')
            imgui.SameLine(0, 8)
            imgui.PushStyleColor(ImGuiCol_Text, { 0.55, 0.58, 0.72, 1.0 })
            imgui.Text('(set BLU as main job to see learn readiness)')
            imgui.PopStyleColor(1)
        end
        imgui.PopStyleColor(1)

        imgui.PushStyleColor(ImGuiCol_Text, { 0.70, 0.73, 0.85, 1.0 })
        imgui.Text(('Learned  %d / %d  (%d%%)'):format(nLearn, total, math.floor(frac * 100 + 0.5)))
        imgui.PopStyleColor(1)
        DrawProgressBar(frac, WINDOW_WIDTH - 24, 10)

        imgui.Spacing()

        -- ---- Filters ----
        -- Line 1: search box + learned/level toggles.
        imgui.SetNextItemWidth(180)
        imgui.InputText('##bm_search', searchBuf, 64)
        if imgui.IsItemHovered() then imgui.SetTooltip('Search name / trait / element / family') end
        imgui.SameLine(0, 12)
        local hl = { cfg.bluemage_hide_learned or false }
        if imgui.Checkbox('Hide learned', hl) then
            cfg.bluemage_hide_learned = hl[1]; settings.save()
        end
        imgui.SameLine(0, 10)
        local ol = { cfg.bluemage_only_my_level or false }
        if imgui.Checkbox('<= my level', ol) then
            cfg.bluemage_only_my_level = ol[1]; settings.save()
        end
        if imgui.IsItemHovered() then imgui.SetTooltip('Only show spells at or below your BLU level.') end

        -- Line 2: tracking mode + the sort/filter dropdowns.
        do
            local curMode  = cfg.bluemage_track_mode or 'off'
            local curLabel = 'Off'
            for _, m in ipairs(TRACK_MODES) do if m[1] == curMode then curLabel = m[2] end end
            imgui.SetNextItemWidth(140)
            if imgui.BeginCombo('##bm_track', 'Track: ' .. curLabel) then
                for _, m in ipairs(TRACK_MODES) do
                    if imgui.Selectable(m[2] .. '##bm_track', curMode == m[1]) then
                        cfg.bluemage_track_mode = m[1]
                        settings.save()
                    end
                end
                imgui.EndCombo()
            end
            if imgui.IsItemHovered() then
                imgui.SetTooltip('Tracker window:\nSpecific = spells you tick in the Trk column\n'
                    .. 'Zone = unlearned spells learnable in your current zone\nOff = hide the tracker')
            end
        end
        imgui.SameLine(0, 6)
        roleFilter  = FilterCombo('Role',  '##bm_role',  roleFilter,  DB.ROLES,    114)
        imgui.SameLine(0, 6)
        famFilter   = FilterCombo('Fam',   '##bm_fam',   famFilter,   DB.FAMILIES, 114)
        imgui.SameLine(0, 6)
        traitFilter = FilterCombo('Trait', '##bm_trait', traitFilter, DB.TRAITS,   150)

